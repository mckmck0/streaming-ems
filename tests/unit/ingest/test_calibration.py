# ── AC-007-17: base-load fit (spec 007, T05; revised in T16 for the two-timescale noise) ──────────

LOAD_SEED = 4242
N_HH = 20
# 90 Europe/Warsaw days with no DST change; the first two weeks hold no PL or DE-NI holiday.
FIT_FIRST = date(2026, 4, 13)
FIT_DAYS = 90
# Generating noise: fast and slow AR(1) (tau_slow fixed at 3 h, as in the fit), slow share w.
TRUE_TAU_H, TRUE_TAU_SLOW_H, TRUE_SLOW_SHARE = 0.6, 3.0, 0.4
TRUE_INTERVAL_SD, TRUE_DAILY_SD = 0.45, 0.05
LOAD_RAW: dict[str, Any] = {
    "reference_annual_kwh": 2300,
    "impulses": {
        "kettle": {"p_kw": 2.0, "dur_min": 3, "rate_per_day": 4.0},
        "oven": {"p_kw": 2.1, "dur_min": 27, "rate_per_day": 0.45},
        "washing_machine": {"p_kw": 2.0, "dur_min": 20, "rate_per_day": 0.41},
    },
    "profiles": {
        "H25": {
            "tau_h": TRUE_TAU_H,
            "tau_slow_h": TRUE_TAU_SLOW_H,
            "slow_share": TRUE_SLOW_SHARE,
            "interval_sd": TRUE_INTERVAL_SD,
            "daily_sd": TRUE_DAILY_SD,
            "impulses": True,
        },
        "G25": {"tau_h": 1.5, "interval_sd": 0.20, "daily_sd": 0.10, "impulses": False},
    },
}
DATASET = {
    "name": "synthetic households (spec 007 test fixture)",
    "licence": "CC BY 4.0",
    "attribution": "generated by ems.ingest.synthetic.load",
}
GAP_LEN = 12  # quarter-hours replaced by a straight line (the WPuQ authors' gap filling)


def _iso_z(t: NDArray[np.int64]) -> NDArray[np.str_]:
    stamps = np.datetime_as_string((t * QUARTER_S).astype("datetime64[s]"), unit="s")
    return np.char.add(stamps, "Z")


def _write_load_csv(path: Path, ids: list[str], t: NDArray[np.int64], kwh: np.ndarray) -> None:
    stamps = _iso_z(t)
    with path.open("w") as f:
        f.write("timestamp_utc,household_id,kwh\n")
        for hh, row in zip(ids, kwh, strict=True):
            f.writelines(f"{s},{hh},{v!r}\n" for s, v in zip(stamps, row.tolist(), strict=True))


def _synthetic_households() -> tuple[list[str], NDArray[np.int64], np.ndarray]:
    """20 H25 households x 90 days from the model, impulses on, one straight-line run each."""
    from ems.ingest.synthetic.load import base_load_kwh, parse_load_params

    params = parse_load_params(LOAD_RAW)
    t0 = quarter_index(local_day_bounds(FIT_FIRST)[0])
    t1 = quarter_index(local_day_bounds(FIT_FIRST + timedelta(days=FIT_DAYS - 1))[1])
    t = np.arange(t0, t1, dtype=np.int64)
    keys = np.array(
        [rng.location_key(f"PL-LOC-{i:06d}") for i in range(1, N_HH + 1)], dtype=np.uint64
    )
    annual = np.linspace(1800.0, 3600.0, N_HH)
    kwh = base_load_kwh(LOAD_SEED, keys, ["H25"] * N_HH, annual, t, params)
    for h in range(N_HH):
        s = 200 + 61 * h
        kwh[h, s : s + GAP_LEN] = np.linspace(kwh[h, s - 1], kwh[h, s + GAP_LEN], GAP_LEN + 2)[1:-1]
    return [f"HH{h + 1:02d}" for h in range(N_HH)], t, kwh


def test_ac_007_17_csv_layout_reads_back(tmp_path: Path) -> None:
    from ems.ingest.calibration import LOAD_COLUMNS, read_load_csv

    assert LOAD_COLUMNS == ("timestamp_utc", "household_id", "kwh")
    ids, t, kwh = _synthetic_households()
    path = tmp_path / "load.csv"
    _write_load_csv(path, ids[:2], t, kwh[:2])
    frame = read_load_csv(path)
    assert tuple(frame.columns) == LOAD_COLUMNS
    assert str(frame["timestamp_utc"].dtype) == "datetime64[ns, UTC]"
    assert frame["kwh"].dtype == np.float64
    assert sorted(frame["household_id"].unique().tolist()) == ids[:2]
    one = frame[frame["household_id"] == ids[1]].sort_values("timestamp_utc")
    expected = pd.to_datetime(t * QUARTER_S, unit="s", utc=True).as_unit("ns")
    assert (one["timestamp_utc"].to_numpy() == expected.to_numpy()).all()
    # pandas' default float parser is not round-trip exact, so allow a few ulps.
    np.testing.assert_allclose(one["kwh"].to_numpy(), kwh[1], rtol=1e-12, atol=0)


def test_ac_007_17_fit_reproduces_full_load_statistics_and_writes_candidate(
    tmp_path: Path,
) -> None:
    """The two time constants trade off, so the fit is judged on the full-load statistics it
    reproduces (AC-007-17), not on recovering the generating parameters.
    """
    from ems.ingest.calibration import fit_load, read_load_csv
    from ems.ingest.synthetic.load import parse_load_params

    ids, t, kwh = _synthetic_households()
    path = tmp_path / "load.csv"
    _write_load_csv(path, ids, t, kwh)
    result = fit_load(
        read_load_csv(path),
        dataset=DATASET,
        model_params=parse_load_params(LOAD_RAW),
        seed=LOAD_SEED,
    )
    assert result["kind"] == "load"
    assert result["households"] == N_HH
    # Fitted noise: tau_fast, slow share, sd and daily sd, with tau_slow fixed.
    assert result["tau_slow_h"] == 3.0
    assert 0 <= result["slow_share"] <= 1, result["slow_share"]
    assert 0 < result["tau_h"] < result["tau_slow_h"], result["tau_h"]
    assert result["interval_sd"] > 0 and result["daily_sd"] >= 0
    # The fitted model's full load (noise and impulses) matches the households'.
    full = result["full_load"]
    assert full["acf_lags_q"] == [1, 2, 4, 8]
    acf_data, acf_model = np.array(full["acf_data"]), np.array(full["acf_model"])
    assert acf_data.shape == acf_model.shape == (4,)
    assert (np.abs(acf_model - acf_data) <= 0.03).all(), (acf_model.tolist(), acf_data.tolist())
    assert abs(full["interval_sd_model"] - full["interval_sd_data"]) <= 0.02, full
    assert abs(full["day_sd_model"] - full["day_sd_data"]) <= 0.03, full
    # One straight-line run per household is masked; ordinary data is not.
    assert 0 < result["masked_share"] < 0.01, result["masked_share"]
    window = result["data_window"]
    assert {"start", "end", "days"} <= set(window)
    assert str(window["start"]) <= str(window["end"]) and 0 < window["days"] <= FIT_DAYS
    assert result["peak_rate_per_day"] > 0
    assert "profile_deviation_sd" in result and "model_peak_rate_per_day" in result
    assert result["dataset"] == DATASET

    out = write_candidate(result, tmp_path / "candidates", "fixture")
    assert out == tmp_path / "candidates" / "load.yaml"
    doc = YAML(typ="safe").load(out.read_text())
    assert doc["kind"] == "load" and doc["households"] == N_HH
    assert doc["dataset"]["licence"] == "CC BY 4.0"
    assert doc["data_window"]["days"] == window["days"]
    for key in (
        "tau_h",
        "tau_slow_h",
        "slow_share",
        "interval_sd",
        "daily_sd",
        "peak_rate_per_day",
    ):
        assert doc[key] == result[key], key
    assert doc["full_load"] == full


WPUQ_T0 = 1546300800  # 2019-01-01T00:00Z, the first stamp of the 2019 file
WPUQ_DTYPE = np.dtype([("index", "<i8"), ("P_TOT", "<f8"), ("Q_TOT", "<f8")])


def _wpuq_table(n: int, nan_at: int | None = None) -> np.ndarray:
    rows = np.zeros(n, dtype=WPUQ_DTYPE)
    rows["index"] = WPUQ_T0 + QUARTER_S * np.arange(n, dtype=np.int64)
    rows["P_TOT"] = 400.0 + 37.5 * np.arange(n)
    rows["Q_TOT"] = 50.0
    if nan_at is not None:
        rows["P_TOT"][nan_at] = np.nan
    return rows


def test_ac_007_17_wpuq_hdf5_reads_like_the_csv(tmp_path: Path) -> None:
    import h5py

    from ems.ingest.calibration import read_load_csv, read_wpuq

    n, nan_at = 20, 7
    table = _wpuq_table(n, nan_at)
    path = tmp_path / "2019_data_15min.hdf5"
    with h5py.File(path, "w") as f:
        f.create_dataset("NO_PV/SFH1/HOUSEHOLD/table", data=table)
        f.create_dataset("NO_PV/SFH6/HOUSEHOLD/table", data=_wpuq_table(n))  # authors' exclusion
        f.create_dataset("WITH_PV/SFH2/HOUSEHOLD/table", data=_wpuq_table(n))  # net of PV feed-in
    frame = read_wpuq(path)
    assert frame["household_id"].unique().tolist() == ["SFH1"]
    assert set(read_wpuq(path, exclude=())["household_id"]) == {"SFH1", "SFH6"}
    frame = frame.sort_values("timestamp_utc").reset_index(drop=True)
    assert len(frame) == n and np.isnan(frame["kwh"].iloc[nan_at])  # gaps stay NaN

    keep = np.arange(n) != nan_at
    csv = tmp_path / "sfh1.csv"
    _write_load_csv(
        csv,
        ["SFH1"],
        (table["index"][keep] // QUARTER_S).astype(np.int64),
        (table["P_TOT"][keep] * 0.25 / 1000).reshape(1, -1),
    )
    pd.testing.assert_frame_equal(
        frame[keep].reset_index(drop=True),
        read_load_csv(csv).sort_values("timestamp_utc").reset_index(drop=True),
        check_exact=False,
        rtol=1e-12,
    )


# ── AC-008-20: forecast-error candidate (spec 008, T21) ───────────────────────────────────────────
# Input: synthetic truth plus spec 007's error model (``forecast_run``), a run every 3 h for 60 days
# at two sites, set up as in tests/property/test_forecast_errors.py. The fit sees only forecast
# events and truth series, so on this input it must recover weather.yaml's sd_x(L) and rho^2.
# Lead L = valid_end - issued_at; bin (lo, hi] holds the steps with lo < L <= hi.
# Margins observed with a reference computation (seeds 1-4 and 11): sd within 4.2 %, rho^2 within
# 0.024, against the ±10 % and ±0.05 of AC-008-20.

WEATHER_YAML = REPO / "config" / "calibration" / "weather.yaml"
WEATHER = load_params(WEATHER_YAML)
FE_SEED = 11
FE_DAYS = 60
FE_SITE_IDS = (1, 2)
FE_CADENCE_Q = 12  # a run every 3 h
FE_RUNS = FE_DAYS * 96 // FE_CADENCE_Q
FE_STEPS = FORECAST_STEPS  # 192 quarter-hours, 48 h
FE_T0 = quarter_index(datetime(2026, 4, 1, tzinfo=UTC))
FE_BIN_H = 3
FE_BINS = [(lo, lo + FE_BIN_H) for lo in range(0, 48, FE_BIN_H)]
FE_LEAD_H = (np.arange(FE_STEPS) + 1) * 0.25  # step k ends (k + 1) quarter-hours after the issue
# One day of site 2's truth is not observed (NaN): its steps are skipped, which n_temp counts.
FE_GAP_SITE = 1  # index into FE_SITE_IDS
FE_GAP = slice(10 * 96, 11 * 96)  # truth axis positions
FE_INGESTED_AT = datetime(2026, 6, 1, tzinfo=UTC)
SD_REL_TOL = 0.10
RHO2_TOL = 0.05
FE_BIN_KEYS = {
    "lead_h",
    "mean_lead_h",
    "n_kt",
    "kt_sd",
    "kt_logit_sd",
    "n_temp",
    "temp_sd",
    "n_wind",
    "wind_ln_sd",
    "rho2_kt",
    "rho2_temp",
    "rho2_wind",
    "hourly_kt_sd",
}
# (bin key, weather.yaml base, weather.yaml per hour): the sds AC-008-20 checks against sd_x(L).
FE_SD_CHECKS = (
    ("temp_sd", "temp_sd_base_c", "temp_sd_per_h_c"),
    ("wind_ln_sd", "wind_ln_sd_base", "wind_ln_sd_per_h"),
)
FE_WEATHER_KEYS = (
    "kt_sd_base",
    "kt_sd_per_h",
    "temp_sd_base_c",
    "temp_sd_per_h_c",
    "wind_ln_sd_base",
    "wind_ln_sd_per_h",
    "rho",
)


def _fe_lead_bin(lo_h: float, hi_h: float) -> NDArray[np.bool_]:
    """Steps whose lead lies in (lo_h, hi_h]."""
    return (lo_h < FE_LEAD_H) & (hi_h >= FE_LEAD_H)


def _fe_location(site_id: int) -> str:
    return f"PL-LOC-{site_id:06d}"


def _fe_sites() -> SiteArrays:
    """The site columns of tests/property/test_forecast_errors.py (values depend on the id)."""
    n = len(FE_SITE_IDS)
    return SiteArrays(
        keys=np.array([rng.location_key(_fe_location(i)) for i in FE_SITE_IDS], dtype=np.uint64),
        lat=np.array([49.5 + (i * 0.37) % 5 for i in FE_SITE_IDS]),
        lon=np.array([14.5 + (i * 0.71) % 9.5 for i in FE_SITE_IDS]),
        elevation_m=np.full(n, 120.0),
        shear_alpha=np.full(n, 0.2),
        wind_scale_ms=np.full(n, 3.4),
    )


def _fe_steps(run: ForecastRun, j: int) -> list[dict[str, Any]]:
    """Step values of site ``j``, rounded as ``ems.ingest.generator._forecast_builders`` does."""
    return [
        {
            "ghi_wm2": round(float(run.ghi[j, k]), 1),
            "dni_wm2": round(float(run.dni[j, k]), 1),
            "dhi_wm2": round(float(run.dhi[j, k]), 1),
            "temp_air_c": round(float(run.temp_c[j, k]), 1),
            "cloud_cover_pct": int(run.cloud_pct[j, k]),
            "wind_speed_ms": {
                "10": round(float(run.wind10[j, k]), 2),
                "100": round(float(run.wind100[j, k]), 2),
                "120": round(float(run.wind120[j, k]), 2),
            },
            "wind_dir_deg": int(run.wind_dir[j, k]) % 360,
        }
        for k in range(run.steps)
    ]


@dataclass(frozen=True)
class ForecastErrorInput:
    events: list[WeatherForecastEvent]
    t0: int  # quarter index of the first truth value
    truth: dict[str, dict[str, F64]]  # location_id -> TruthSeries fields (ghi, cs_ghi, ...)
    n_temp: dict[int, int]  # bin lower edge -> steps with an observed temperature (both sites)


@pytest.fixture(scope="module")
def forecast_error_input() -> ForecastErrorInput:
    """480 runs x 2 sites of synthetic forecasts and the truth they were drawn from (~2 s)."""
    site = _fe_sites()
    n_axis = (FE_RUNS - 1) * FE_CADENCE_Q + FE_STEPS + truth_margin_q(WEATHER)
    truth = generate_truth(site, TimeAxis.from_range(FE_T0, n_axis), FE_SEED, WEATHER)
    events: list[WeatherForecastEvent] = []
    for r in range(FE_RUNS):
        issue = FE_T0 + r * FE_CADENCE_Q
        run = forecast_run(truth, issue, FE_STEPS, FE_SEED, site.keys, WEATHER)
        for j, site_id in enumerate(FE_SITE_IDS):
            events.append(
                forecast_event(
                    location_id=_fe_location(site_id),
                    issued_at=from_quarter_index(issue),
                    steps=_fe_steps(run, j),
                    ingested_at=FE_INGESTED_AT,
                    forecast_model="synthetic",
                )
            )
    series: dict[str, dict[str, F64]] = {}
    for j, site_id in enumerate(FE_SITE_IDS):
        fields = {
            "ghi": truth.ghi[j].copy(),
            "cs_ghi": truth.geometry.cs_ghi[j].copy(),
            "temp_c": truth.temp_c[j].copy(),
            "wind10": truth.wind10[j].copy(),
        }
        if j == FE_GAP_SITE:
            for name in ("ghi", "temp_c", "wind10"):  # clear-sky is computed, never missing
                fields[name][FE_GAP] = np.nan
        series[_fe_location(site_id)] = fields
    # Expected temperature pairs per bin: every (run, step) whose valid quarter has a truth value.
    valid_pos = np.arange(FE_RUNS)[:, None] * FE_CADENCE_Q + np.arange(FE_STEPS)[None, :]
    observed = np.stack([np.isfinite(f["temp_c"])[valid_pos] for f in series.values()])
    n_temp = {lo: int(observed[:, :, _fe_lead_bin(lo, hi)].sum()) for lo, hi in FE_BINS}
    return ForecastErrorInput(events=events, t0=int(truth.axis.t[0]), truth=series, n_temp=n_temp)


def _truth_series(inp: ForecastErrorInput) -> dict[str, Any]:
    from ems.ingest.calibration import TruthSeries

    return {loc: TruthSeries(t0=inp.t0, **fields) for loc, fields in inp.truth.items()}


def _finite_or_none(value: Any) -> bool:
    return value is None or (isinstance(value, float | int) and math.isfinite(value))


def test_ac_008_20_fit_recovers_the_spec_007_forecast_error_model(
    forecast_error_input: ForecastErrorInput,
) -> None:
    """AC-008-20: per 3-hour lead bin, temperature and wind sd within ±10 % of weather.yaml's
    sd_x(mean_lead_h) and the consecutive-run correlation within ±0.05 of rho^2 (bins from 3 h
    on; the 45-48 h bin has no older run at 48-51 h). Steps with NaN truth are skipped.
    """
    from ems.ingest.calibration import fit_forecast_error

    inp = forecast_error_input
    result = fit_forecast_error(inp.events, _truth_series(inp), WEATHER)
    assert result["kind"] == "forecast-error"
    assert set(result["models"]) == {"synthetic"}
    model = result["models"]["synthetic"]
    bins = model["bins"]
    assert [list(b["lead_h"]) for b in bins] == [[lo, hi] for lo, hi in FE_BINS]

    fp = WEATHER["forecast"]
    rho2 = float(fp["rho"]) ** 2
    bad: list[str] = []
    for (lo, hi), b in zip(FE_BINS, bins, strict=True):
        assert set(b) >= FE_BIN_KEYS, (lo, sorted(FE_BIN_KEYS - set(b)))
        assert all(_finite_or_none(b[k]) for k in FE_BIN_KEYS - {"lead_h"}), (lo, b)
        lead = b["mean_lead_h"]
        assert lo < lead <= hi, (lo, lead)
        # Every step pairs with the truth at quarter_index(valid_start) unless that truth is NaN.
        assert b["n_temp"] == inp.n_temp[lo], (lo, b["n_temp"], inp.n_temp[lo])
        assert 0 < b["n_wind"] <= b["n_temp"] and 0 < b["n_kt"] < b["n_temp"], (lo, b)
        # Daylight kt: the logit slope is >= 4 / 1.07 everywhere, so the logit sd is the larger.
        assert 0 < b["kt_sd"] < b["kt_logit_sd"], (lo, b["kt_sd"], b["kt_logit_sd"])
        assert b["hourly_kt_sd"] is not None and b["hourly_kt_sd"] > 0, (lo, b["hourly_kt_sd"])
        for key, base, per_h in FE_SD_CHECKS:
            expected = float(fp[base]) + float(fp[per_h]) * lead
            if abs(b[key] / expected - 1) > SD_REL_TOL:
                bad.append(f"{lo}-{hi} h {key}={b[key]:.4f}, sd(L={lead:.3f})={expected:.4f}")
        for var in ("kt", "temp", "wind"):
            value = b[f"rho2_{var}"]
            if hi + FE_BIN_H > 48:  # the older run would need a lead beyond 48 h
                assert value is None, (lo, var, value)
                continue
            assert value is not None, (lo, var)
            if var != "kt" and lo >= 3 and abs(value - rho2) > RHO2_TOL:
                bad.append(f"{lo}-{hi} h rho2_{var}={value:.4f}, rho^2={rho2:.4f}")
    assert not bad, bad

    fit = model["fit"]
    for name in ("kt_logit", "temp", "wind_ln"):
        assert {"base", "per_h"} <= set(fit[name]), (name, fit[name])
        assert all(math.isfinite(fit[name][k]) for k in ("base", "per_h")), (name, fit[name])
    assert fit["temp"]["per_h"] > 0, fit["temp"]


def test_ac_008_20_candidate_carries_assumptions_and_caveats_and_leaves_weather_yaml(
    forecast_error_input: ForecastErrorInput, tmp_path: Path
) -> None:
    """AC-008-20: the candidate holds weather.yaml's assumed values and the caveats (satellite and
    ERA5 truth error, DMI's interpolated 15-minute radiation, sds are upper bounds), is written as
    candidates/forecast-error.yaml, and weather.yaml stays byte-identical.
    """
    from ems.ingest.calibration import fit_forecast_error

    before = WEATHER_YAML.read_bytes()
    inp = forecast_error_input
    result = fit_forecast_error(inp.events, _truth_series(inp), WEATHER)

    fp = WEATHER["forecast"]
    assumed = result["weather_yaml"]
    assert {k: assumed.get(k) for k in FE_WEATHER_KEYS} == {k: fp[k] for k in FE_WEATHER_KEYS}
    caveats = result["caveats"]
    assert isinstance(caveats, list) and caveats and all(isinstance(c, str) for c in caveats)
    text = " ".join(caveats)
    assert "satellite" in text.lower(), caveats
